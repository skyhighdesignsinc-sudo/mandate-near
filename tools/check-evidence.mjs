// tools/check-evidence.mjs — every transaction hash we cite must resolve on chain.
//
// This exists because a hash can be well-formed and still be nothing: the id is
// base58(sha256(bytes)), which can be computed before a transaction is accepted.
// A retry, a stale nonce or a tolerated broadcast error is enough to leave a
// perfect-looking hash behind that no explorer will ever open.
//
//   node tools/check-evidence.mjs thesis/data/spends.json JUDGE.md
//   node tools/check-evidence.mjs --markdown docs/EVIDENCE-CHECK.md <paths...>
//
// Exit codes: 0 every hash resolved, 1 at least one did not, 2 the check could
// not run (no endpoint answered) — never 0 on an inconclusive run.
import { readFileSync, writeFileSync } from 'node:fs';

const RPC = [
  process.env.NEAR_RPC ?? 'https://rpc.testnet.fastnear.com',
  'https://rpc.testnet.near.org',
];

const SIGNERS = ['mandate-hackaton-7c1a.testnet'];
const BASE58 = /^[1-9A-HJ-NP-Za-km-z]{43,44}$/;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const args = process.argv.slice(2);
const markdownAt = args.includes('--markdown') ? args[args.indexOf('--markdown') + 1] : null;
const paths = args.filter((a) => !a.startsWith('--') && a !== markdownAt);

if (!paths.length) {
  console.error('usage: node tools/check-evidence.mjs [--markdown <out.md>] <file...>');
  process.exit(2);
}

async function rpcOnce(endpoint, method, params) {
  const res = await fetch(endpoint, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 'check-evidence', method, params }),
  });
  return res.json();
}

async function findTx(hash) {
  let reachable = false;
  for (const endpoint of RPC) {
    for (const signer of SIGNERS) {
      try {
        const body = await rpcOnce(endpoint, 'tx', {
          tx_hash: hash,
          sender_account_id: signer,
          wait_until: 'NONE',
        });
        if (body.result?.transaction_outcome) {
          return {
            found: true,
            endpoint,
            method: body.result.transaction?.actions?.[0]?.FunctionCall?.method_name ?? '?',
            block: body.result.transaction_outcome.block_hash,
            outcome: body.result.transaction_outcome.outcome?.status,
          };
        }
        reachable = true;
      } catch {
        /* network hiccup: try the next endpoint */
      }
    }
    await sleep(60);
  }
  return { found: false, reachable };
}

// Only hashes that are cited as transactions. Scanning for "anything that fits
// the alphabet" picks up vendor addresses and hex digests, which are not
// evidence and would make this check cry wolf.
function citedHashes(path) {
  const raw = readFileSync(path, 'utf8');
  const found = new Set();

  for (const m of raw.matchAll(/txns\/([1-9A-HJ-NP-Za-km-z]{43,44})/g)) found.add(m[1]);
  for (const m of raw.matchAll(/"tx(?:Hash)?"\s*:\s*"([1-9A-HJ-NP-Za-km-z]{43,44})"/g)) found.add(m[1]);
  // Markdown cites a hash as `HASH`; that is a citation and must be checked too.
  for (const m of raw.matchAll(/`([1-9A-HJ-NP-Za-km-z]{43,44})`/g)) found.add(m[1]);

  if (path.endsWith('.json')) {
    try {
      const walk = (node) => {
        if (Array.isArray(node)) return node.forEach(walk);
        if (node && typeof node === 'object') {
          for (const [key, value] of Object.entries(node)) {
            if ((key === 'tx' || key === 'txHash') && typeof value === 'string' && BASE58.test(value)) {
              found.add(value);
            } else {
              walk(value);
            }
          }
        }
      };
      walk(JSON.parse(raw));
    } catch {
      /* not JSON: the regexes above already covered it */
    }
  }
  return [...found];
}

const rows = [];
const seen = new Set();
let unreachable = 0;

for (const path of paths) {
  const candidates = citedHashes(path);
  for (const hash of candidates) {
    if (seen.has(hash)) continue;
    seen.add(hash);
    const result = await findTx(hash);
    if (!result.found && result.reachable === false) unreachable += 1;
    rows.push({ path, hash, ...result });
    const label = result.found ? 'RESOLVES' : 'MISSING ';
    console.log(`${label} ${hash.slice(0, 10)}…  ${path}${result.found ? `  ${result.method}` : ''}`);
    await sleep(90);
  }
}

const found = rows.filter((r) => r.found).length;
const missing = rows.filter((r) => !r.found);
const ok = missing.length === 0 && rows.length > 0;

console.log('');
console.log(`  hashes checked: ${rows.length}`);
console.log(`  resolve on chain: ${found}`);
console.log(`  do not resolve:   ${missing.length}`);
if (unreachable) console.log(`  endpoint-unreachable: ${unreachable}`);
console.log('');

if (markdownAt) {
  const lines = [
    '# Evidence check',
    '',
    `Generated by \`node tools/check-evidence.mjs\` on ${new Date().toISOString()}.`,
    'A hash counts only if a public testnet RPC returns its transaction outcome.',
    '',
    `**${found} of ${rows.length} hashes resolve. ${missing.length} do not.**`,
    '',
    '| File | Hash | Result | Method |',
    '|---|---|---|---|',
    ...rows.map(
      (r) =>
        `| \`${r.path}\` | \`${r.hash}\` | ${r.found ? 'resolves' : '**does not resolve**'} | ${r.found ? r.method : '—'} |`,
    ),
    '',
  ];
  writeFileSync(markdownAt, lines.join('\n'));
  console.log(`  wrote ${markdownAt}`);
}

if (!rows.length) {
  console.log('  no hashes found — treating as inconclusive.');
  process.exit(2);
}
process.exit(ok ? 0 : 1);
